import { expect, test } from '@playwright/test';

test('fresh measured evidence scores, persists, reviews and exports', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByRole('button', { name: 'Score a New Cut', exact: true }).click();
  await expect(page.getByText('Unconfigured — commissioning pending', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Load measured example', exact: true }).click();
  await expect(page.getByLabel('Completed-cut JSON')).not.toHaveValue('');
  const evidence = JSON.parse(await page.getByLabel('Completed-cut JSON').inputValue());
  expect(evidence.events[0].tool_life_id).toMatch(/^new-tool-life-/);
  expect(Object.keys(evidence.events[0].features)).toHaveLength(72);
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  const card = page.locator('.fresh-workspace article').first();
  await expect(card).toContainText('review recommended');
  await expect(card).toContainText('58.2%');
  await card.getByRole('button', { name: 'Approve inspection', exact: true }).click();
  await expect(card).toContainText('Review · approved');
  await page.getByLabel('Fresh inspection finding').fill('Benchmark workflow exercise; no physical inspection performed.');
  await card.getByRole('button', { name: 'Complete inspection', exact: true }).click();
  await expect(card).toContainText('Review · completed');
  const href = await card.getByRole('link', { name: 'Export assessment' }).getAttribute('href');
  const exported = await (await page.request.get(href!)).json();
  expect(exported.evidence).toEqual(evidence.events[0]);
  expect(exported.assessment.review.history.map((entry: { action: string }) => entry.action)).toEqual(['approve', 'complete']);
  await page.reload();
  await page.getByRole('button', { name: 'Score a New Cut', exact: true }).click();
  await expect(page.locator('.fresh-workspace article').first()).toContainText('Review · completed');
  await page.screenshot({ path: 'test-results/kerfpulse-fresh-assessment.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});

test('upload and validation distinguish unsupported evidence from a forecast', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Score a New Cut', exact: true }).click();
  await page.getByRole('button', { name: 'Load unsupported example', exact: true }).click();
  await expect(page.getByLabel('Completed-cut JSON')).not.toHaveValue('');
  const evidence = await page.getByLabel('Completed-cut JSON').inputValue();
  await page.getByLabel('Upload measured file').setInputFiles({ name: 'measured.json', mimeType: 'application/json', buffer: Buffer.from(evidence) });
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  const card = page.locator('.fresh-workspace article').first();
  await expect(card).toContainText('unsupported domain');
  await expect(card.getByText('Unavailable', { exact: true })).toHaveCount(2);
  await expect(card.getByRole('button', { name: 'Approve inspection' })).toHaveCount(0);
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download CSV template', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('kerfpulse-cut-template.csv');
  await page.getByLabel('Upload measured file').setInputFiles({ name: 'bad.csv', mimeType: 'text/csv', buffer: Buffer.from('event_id,event_id\na,b\n') });
  await expect(page.getByRole('alert')).toContainText('must be unique');
  await page.getByLabel('Completed-cut JSON').fill('{ broken');
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('SyntaxError');
});

test('CSV partial validation, dismissal, templates and request failure recover visibly', async ({ page }) => {
  await page.goto('/');
  await page.getByRole('button', { name: 'Score a New Cut', exact: true }).click();
  const schema = await (await page.request.get('/api/fresh/schema')).json();
  const event = schema.example;
  const metadata = Object.keys(event).filter(key => !['context', 'features'].includes(key));
  const columns = [...metadata, ...schema.context_fields, ...schema.feature_fields];
  const flattened = { ...event, inspection_breaks: event.inspection_breaks.join(';'), ...event.context, ...event.features };
  const bad = { ...flattened, event_id: 'invalid-second-row', HardnessMean: '' };
  const quote = (v: unknown) => '"' + String(v ?? '').replaceAll('"', '""') + '"';
  const csv = [columns.map(quote).join(','), ...[flattened, bad].map(row => columns.map(key => quote(row[key])).join(','))].join('\r\n');
  await expect(page.getByLabel('Upload measured file')).toBeEnabled();
  await page.getByLabel('Upload measured file').setInputFiles({ name: 'cuts.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) });
  await expect(page.getByLabel('Completed-cut JSON')).toHaveValue(/invalid-second-row/);
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Row 2 · context');
  const card = page.locator('.fresh-workspace article');
  await expect(card).toHaveCount(1);
  await card.getByRole('button', { name: 'Dismiss inspection', exact: true }).click();
  await expect(card).toContainText('Review · dismissed');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download JSON template', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('kerfpulse-cut-template.json');
  await page.route('**/api/fresh/assessments', route => route.request().method() === 'POST' ? route.abort('failed') : route.continue());
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText(/Failed to fetch|NetworkError/);
  await page.unroute('**/api/fresh/assessments');
  await page.getByRole('button', { name: 'Validate and score', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('Row 2 · context');
  await expect(card).toHaveCount(1);
});
